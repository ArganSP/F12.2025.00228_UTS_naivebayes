for tr, va in skf.split(X_train, y_train):
    Xtr, Xva = X_train.iloc[tr], X_train.iloc[va]
    ytr, yva = y_train.iloc[tr], y_train.iloc[va]
    m_a = GaussianNB().fit(Xtr, ytr)
    m_b = GaussianNB().fit(Xtr, ytr, sample_weight=ytr.map(class_weights).values)
    cv_a.append(f1_score(yva, m_a.predict(Xva), average="macro"))
    cv_b.append(f1_score(yva, m_b.predict(Xva), average="macro"))
    cv_acc_a.append(accuracy_score(yva, m_a.predict(Xva)))
    cv_acc_b.append(accuracy_score(yva, m_b.predict(Xva)))

