labels = [0, 1, 2, 3]

def ringkas(nama, y_true, y_pred):
    rec = [(y_pred[(y_true.values == k)] == k).mean() for k in labels]
    return {"model": nama,
            "akurasi": round(accuracy_score(y_true, y_pred), 4),
            "macro F1": round(f1_score(y_true, y_pred, average="macro"), 4),
            "weighted F1": round(f1_score(y_true, y_pred, average="weighted"), 4),
            "QWK": round(cohen_kappa_score(y_true, y_pred, weights="quadratic"), 4),
            **{f"recall {s}": round(r, 4) for s, r in zip(short, rec)}}

baseline_acc = (y_test == 2).mean()
print(f"Baseline (selalu menebak Standard-Compliant): akurasi = {baseline_acc:.4f}\n")

hasil = pd.DataFrame([ringkas("A: GaussianNB standar", y_test, y_pred_a),
                      ringkas("B: GaussianNB + bobot kelas", y_test, y_pred_b)]).set_index("model")
hasil.T

